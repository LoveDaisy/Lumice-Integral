def test_warm_seed_from_the_row_above_is_a_newton_start_not_a_separate_trace(
    canonical_discovery: ComponentDiscoveryResult,
) -> None:
    seed = canonical_discovery.components[0].seed
    cold = discover_pixel(151, 150)
    warm = discover_pixel(151, 150, extra_seeds=[seed])
    assert cold.extra_seed_count == 0 and warm.extra_seed_count == 1
    assert warm.pool_count == cold.pool_count  # the table pool is unchanged
    assert cold.component_count == warm.component_count == 1
    assert cold.components[0].arclength == pytest.approx(ROW_151_ARCLENGTH, rel=ARCLENGTH_RTOL)
    assert warm.components[0].arclength == pytest.approx(cold.components[0].arclength, rel=1e-9)
    assert warm.components[0].arclength != pytest.approx(CANONICAL_ARCLENGTH, rel=1e-4)
    # The warm seed's cluster is traced first, from the warm seed itself.
    assert distance_to_curve(warm.components[0].seed, np.asarray([seed])) < 0.05
    assert warm.events["dedup_merged"] == warm.admissible_count - 1


