def _closed_record(arclength: float, poses: int) -> DiscoveredComponent:
    return DiscoveredComponent(
        seed=np.eye(3),
        result=SimpleNamespace(poses=np.zeros((poses, 3, 3))),
        arclength=arclength,
        status=FiberStatus.CLOSED,
        reason=TerminationReason.CLOSED_LOOP,
    )


def _incomplete_record(reason: TerminationReason = TerminationReason.STEP_BUDGET) -> IncompleteCandidate:
    return IncompleteCandidate(
        seed=np.eye(3),
        result=SimpleNamespace(poses=np.zeros((251, 3, 3))),
        status=FiberStatus.BUDGET_EXHAUSTED,
        reason=reason,
    )


