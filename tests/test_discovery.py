def test_rows_225_and_226_are_one_continuous_branch_without_an_arclength_jump(
    row_225_discovery: ComponentDiscoveryResult, row_226_discovery: ComponentDiscoveryResult
) -> None:
    # The "topology boundary" this pair used to exhibit (6.24 -> 3.13, about
    # 50 %) was the absolute closure gate closing row 225's 3.12 loop on its
    # second traversal while row 226's 3.13 loop, just above pi, closed once
    # (task-continuation-gates-and-fixtures).  With the relative gate the two
    # rows differ by well under 1 %; the retired artifact is kept below as the
    # jump the detector was calibrated on.
    for result in (row_225_discovery, row_226_discovery):
        assert result.completeness == "complete"
        assert result.component_count == 1
    upper = row_225_discovery.components[0].arclength
    lower = row_226_discovery.components[0].arclength
    assert upper == pytest.approx(ROW_225_ARCLENGTH, rel=ARCLENGTH_RTOL)
    assert lower == pytest.approx(ROW_226_ARCLENGTH, rel=ARCLENGTH_RTOL)
    assert abs(upper - lower) < 0.01 * lower
    assert detect_arclength_jump([upper, lower]) == []
    assert detect_arclength_jump([2.0 * upper, lower]) == [0]


