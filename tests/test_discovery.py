def test_distance_to_curve_is_the_minimum_over_the_sampled_poses() -> None:
    axis = np.array([0.0, 0.0, 1.0])
    poses = np.stack([np.asarray(exp(jnp.asarray(theta * axis))) for theta in np.linspace(0.0, 1.0, 11)])
    on_curve = np.asarray(exp(jnp.asarray(0.55 * axis)))  # halfway between two samples 0.1 apart
    assert distance_to_curve(on_curve, poses) == pytest.approx(0.05, abs=1e-12)
    off_curve = poses[5] @ np.asarray(exp(jnp.asarray(np.array([0.3, 0.0, 0.0]))))  # 0.3 off sample 5
    assert distance_to_curve(off_curve, poses) == pytest.approx(0.3, abs=1e-9)
    assert distance_to_curve(poses[3], poses) == pytest.approx(0.0, abs=1e-12)


# --- the closed / arc / incomplete branches on an analytic two-sided arc ----------


def _constant(value: float) -> WeightEvaluator:
    return WeightEvaluator(lambda _: value, "dimensionless", "test constant")


def _circle_angle(rotation) -> float:
    rotation = np.asarray(rotation)
    return float(np.arctan2(rotation[1, 0], rotation[0, 0]))


def _capped_circle(
    theta_min: float | None,
    theta_max: float | None,
    *,
    hi_kind: TerminationReason = TerminationReason.VISIBILITY_BOUNDARY,
    lo_kind: TerminationReason = TerminationReason.TIR_BOUNDARY,
) -> FiberProblem:
    """The analytic body-axis circle, cut at ``theta_min``/``theta_max`` (``None`` = uncut)."""

    def domain(rotation):
        theta = _circle_angle(rotation)
        margins = {}
        if theta_max is not None:
            margins["cap_hi"] = theta_max - theta
        if theta_min is not None:
            margins["cap_lo"] = theta - theta_min
        if theta_max is not None and margins["cap_hi"] < 0.0:
            return DomainEvaluation(False, margins, EventCandidate(hi_kind, margins["cap_hi"]))
        if theta_min is not None and margins["cap_lo"] < 0.0:
            return DomainEvaluation(False, margins, EventCandidate(lo_kind, margins["cap_lo"]))
        return DomainEvaluation(True, margins)

    return FiberProblem(
        path="analytic-body-axis",
        incident_direction=jnp.array([1.0, 0.0, 0.0], dtype=jnp.float64),
        target_chart=TargetChart(BODY_AXIS, tangent_basis(BODY_AXIS)),
        direction_evaluator=direction_map,
        seed=jnp.eye(3, dtype=jnp.float64),
        domain_and_event_evaluator=domain,
        weight_evaluators={"rho_pose": _constant(1.0)},
    )


def _classify(problem: FiberProblem, options: ContinuationOptions | None = None):
    from collections import Counter

    events: Counter = Counter()
    timings: Counter = Counter()
    record = _trace_and_classify(problem, options or ContinuationOptions(), np.eye(3), events, timings)
    return record, events, timings


def test_two_named_events_stitch_into_an_arc_component() -> None:
    record, events, timings = _classify(_capped_circle(-1.3, 2.0))
    assert isinstance(record, DiscoveredComponent) and record.kind == "arc"
    assert events["arc_stitched"] == 1 and timings["trace_s"] > 0.0
    arc = record.result
    assert isinstance(arc, OpenArc)
    assert record.status == FiberStatus.EVENT_TERMINATED
    assert record.reason == TerminationReason.VISIBILITY_BOUNDARY
    assert record.start_reason == TerminationReason.TIR_BOUNDARY
    assert arc.forward.reason == TerminationReason.VISIBILITY_BOUNDARY
    assert arc.backward.reason == TerminationReason.TIR_BOUNDARY
    # White-box: the stitched arrays run monotonically from the backward end
    # through the seed to the forward end, every tangent points along +theta,
    # and the increments are the chords between consecutive poses.
    thetas = np.array([_circle_angle(pose) for pose in arc.poses])
    assert np.all(np.diff(thetas) > 0.0)
    assert -1.3 <= thetas[0] < 0.0 < thetas[-1] <= 2.0
    assert np.allclose(arc.poses[arc.seed_index], np.eye(3), atol=1e-12)
    assert np.all(arc.tangents @ np.array([0.0, 0.0, 1.0]) > 0.99)
    assert np.allclose(arc.arclength_increments, np.diff(thetas), atol=1e-10)
    assert record.arclength == pytest.approx(thetas[-1] - thetas[0], abs=1e-10)
    assert len(arc.branch_diagnostics.accepted_margins) == len(arc.poses)
    assert len(arc.poses) == len(arc.forward.poses) + len(arc.backward.poses) - 1


def test_closed_loop_is_a_closed_component_without_a_backward_trace() -> None:
    record, events, _ = _classify(_capped_circle(None, None))
    assert isinstance(record, DiscoveredComponent) and record.kind == "closed"
    assert record.status == FiberStatus.CLOSED and record.start_reason is None
    assert record.arclength == pytest.approx(2.0 * np.pi, rel=1e-6)
    assert not any(events.values())


def test_backward_trace_that_does_not_end_on_a_named_event_leaves_the_candidate_incomplete() -> None:
    # Cut on the forward side only: the backward trace runs until its
    # arclength budget (no event) -> incomplete, both traces kept.
    options = ContinuationOptions(maximum_arclength=1.0)
    record, events, _ = _classify(_capped_circle(None, 0.5), options)
    assert isinstance(record, IncompleteCandidate)
    assert record.cause == "arc_backward_failed" and events["arc_backward_failed"] == 1
    assert record.reason == TerminationReason.VISIBILITY_BOUNDARY
    assert record.backward is not None
    assert record.backward.status == FiberStatus.BUDGET_EXHAUSTED
    assert record.backward.reason == TerminationReason.ARCLENGTH_BUDGET


def test_unnamed_event_is_incomplete_and_not_traced_backward(monkeypatch) -> None:
    calls = []
    real_trace = trace_fiber

    def counting_trace(problem, options=None, *args, **kwargs):
        calls.append(options.initial_tangent_sign if options is not None else 1)
        return real_trace(problem, options, *args, **kwargs)

    monkeypatch.setattr(discovery_module, "trace_fiber", counting_trace)
    record, events, _ = _classify(_capped_circle(None, 0.5, hi_kind=TerminationReason.RANK_LOSS))
    assert isinstance(record, IncompleteCandidate)
    assert record.cause == "incomplete_unnamed_event" and events["incomplete_unnamed_event"] == 1
    assert record.reason == TerminationReason.RANK_LOSS and record.backward is None
    assert calls == [1]


def test_backward_trace_that_closes_is_an_anomaly_not_a_component(monkeypatch) -> None:
    forward = trace_fiber(_capped_circle(None, 0.5))
    closed = trace_fiber(_capped_circle(None, None))
    assert forward.reason == TerminationReason.VISIBILITY_BOUNDARY and closed.status == FiberStatus.CLOSED

    def fake_trace(problem, options=None, *args, **kwargs):
        return closed if options is not None and options.initial_tangent_sign == -1 else forward

    monkeypatch.setattr(discovery_module, "trace_fiber", fake_trace)
    record, events, _ = _classify(_capped_circle(None, 0.5))
    assert isinstance(record, IncompleteCandidate)
    assert record.cause == "arc_backward_closed_anomaly" and events["arc_backward_closed_anomaly"] == 1
    assert record.backward is closed and record.result is forward


