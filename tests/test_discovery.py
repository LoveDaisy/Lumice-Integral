# --- Step 5: discovery budget is independent of the production budget ----------


def test_discovery_budget_and_production_budget_are_independent_options() -> None:
    problem = canonical_pixel_problem(with_weights=False)
    small = ContinuationOptions(maximum_accepted_steps=50)
    production = ContinuationOptions()
    assert small is not production
    assert production.maximum_accepted_steps == 4000
    truncated = trace_fiber(problem, small)
    assert truncated.status == FiberStatus.BUDGET_EXHAUSTED
    assert truncated.reason == TerminationReason.STEP_BUDGET
    assert len(truncated.poses) == 51
    closed = trace_fiber(problem, production)
    assert closed.status == FiberStatus.CLOSED
    assert float(closed.arclength_increments.sum()) == pytest.approx(CANONICAL_ARCLENGTH, rel=ARCLENGTH_RTOL)
    assert small.maximum_accepted_steps == 50


