def test_band_coverage_reports_a_component_discovery_did_not_return() -> None:
    """Remove the (only) traced loop from the result: every band event becomes a suspect on the fiber."""
    target = pixel_target(49, 0)  # a 0.19 rad loop at the caustic, its events up to 0.117 rad off the curve as posed
    found = discover_pixel(49, 0)
    complete = check_band_coverage(target, SEEDS, found)
    assert complete.suspect_count == 0 and complete.corrected_count > 0 and complete.on_curve_count == complete.corrected_count
    missed = check_band_coverage(target, SEEDS, dataclasses.replace(found, components=()))
    assert missed.suspect_count == missed.event_count == found.pool_count and missed.suspect_clusters >= 1
    assert missed.component_event_counts == () and missed.miss_probability_bound is None
    # The suspects are fiber poses on the loop that was removed.
    assert max(distance_to_curve(seed, np.asarray(found.components[0].result.poses)) for seed in missed.suspects) < 0.08


